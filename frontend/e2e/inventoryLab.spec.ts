import { test, expect } from '@playwright/test'

test('real inventory intent replay, conflicts, terminal states and audit', async ({ page }) => {
  await page.goto('/inventory-lab')
  await page.getByLabel('初始库存', { exact: true }).fill('2')
  await page.getByTestId('inventory-new-scenario').click()
  await expect(page.getByTestId('inventory-result')).toContainText('"initial": 2')
  await page.getByTestId('inventory-prepare').click()
  const key = await page.getByTestId('inventory-intent-key').textContent()
  await page.getByTestId('inventory-submit').click()
  await expect(page.getByTestId('inventory-result')).toContainText('"applied": true')
  await expect(page.getByTestId('inventory-order-state')).toHaveText('reserved')
  await page.getByTestId('inventory-submit').click()
  await expect(page.getByTestId('inventory-result')).toContainText('"replayed": true')
  await expect(page.getByTestId('inventory-intent-key')).toHaveText(key!)
  await page.getByLabel('下单数量', { exact: true }).fill('2')
  await page.getByRole('button', { name: '冲突实验：原键 + 当前参数', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('idempotency_conflict')
  await page.getByRole('button', { name: '取消并归还预留', exact: true }).click()
  await expect(page.getByTestId('inventory-order-state')).toHaveText('cancelled')
  await page.getByRole('button', { name: '取消并归还预留', exact: true }).click()
  await expect(page.getByTestId('inventory-result')).toContainText('"applied": false')
  await page.getByLabel('下单数量', { exact: true }).fill('1')
  await page.getByTestId('inventory-prepare').click()
  await page.getByTestId('inventory-submit').click()
  await expect(page.getByTestId('inventory-result')).toContainText('"applied": true')
  await page.locator('.event-row').filter({ hasText: 'MySQL SQL + 变更' }).first().click()
  await expect(page.getByTestId('business-sql')).toContainText('INSERT INTO purchase_order')
  await expect(page.locator('.inspector')).toContainText('实际影响 1 行')
  await page.getByRole('button', { name: '标记 paid（实验）', exact: true }).click()
  await expect(page.getByTestId('inventory-order-state')).toHaveText('paid')
  await page.getByRole('button', { name: '取消并归还预留', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('invalid_order_transition')
  await page.getByTestId('inventory-audit').click()
  await expect(page.getByTestId('inventory-audit-result')).toContainText('所有审计项通过')
  await expect(page.getByTestId('inventory-audit-result')).toContainText('"paid": 1')
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({
    path: '../docs/experiments/007-inventory-idempotency/inventory-lab.png',
    fullPage: true,
  })
})

test('bounded client contest checks persisted audit and does not count replays as new stock', async ({
  page,
}) => {
  await page.goto('/inventory-lab')
  await page.getByLabel('初始库存', { exact: true }).fill('3')
  await page.getByTestId('inventory-new-scenario').click()
  await expect(page.getByTestId('inventory-result')).toContainText('"initial": 3')
  await page.getByTestId('inventory-contest').click()
  await expect(page.getByTestId('inventory-audit-result')).toContainText('所有审计项通过')
  await expect(page.getByText('确认唯一订单 3', { exact: false })).toBeVisible()
  await expect(page.getByTestId('inventory-stock')).toContainText('可用 0')
  await expect(page.getByTestId('inventory-stock')).toContainText('预留 3')
})
